//! 許可クレートの初回準備の手順（spec/exercise-runner/crates-and-workspace.md「初回準備」の「手順」）を、
//! 実物の `cargo`（このテストを動かしている cargo）と偽の `cargo` で確かめる。
//!
//! - 許可クレートが空の一覧のテストは、ネットワークを使わない。
//! - 名前が `with_network_` で始まるテストは、同梱の一覧（`rand`）をダウンロードするので、ネットワークが要る
//!   （CI はネットワークを使える）。
//! - 手順の 4（`target-validate/` の複製）を含むテストは、`cp -c`（APFS のクローン）が macOS にしか無いので、
//!   macOS のときだけ実行する（spec/non-functional/testing.md「CI」）。

#[path = "fake_tools/rust.rs"]
mod fake_rust;

use std::collections::BTreeMap;
use std::fs;
use std::path::{Path, PathBuf};
use std::process::Command;

use fake_rust::FakeRust;
use progrust_lib::runner::RunnerDir;
use progrust_lib::runner::preparation::{PreparationOutcome, PreparationSpec, prepare};
use progrust_lib::runner::prepared::{
    PreparedRecord, PreparedStatus, crates_hash, read_prepared, rustc_verbose_version,
};
use progrust_lib::runner::process::Stopper;
use progrust_lib::runner::project::{assemble_project, build_env};
use progrust_lib::runner::workspace::WorkspaceDir;
use tempfile::TempDir;

/// 許可クレートが空の一覧。
const EMPTY_ALLOWED_CRATES: &str = "[dependencies]\n";
/// 空の一覧に合う `Cargo.lock`（`allcrates/` をルートのパッケージにして生成したもの）。
const EMPTY_CARGO_LOCK: &str = "# This file is automatically @generated by Cargo.\n\
# It is not intended for manual editing.\n\
version = 4\n\
\n\
[[package]]\n\
name = \"progrust_allowed_crates\"\n\
version = \"0.1.0\"\n";

/// このテストを動かしている cargo と、その隣の rustc。
fn real_cargo() -> (PathBuf, PathBuf) {
    let cargo = PathBuf::from(env!("CARGO"));
    let rustc = cargo.with_file_name("rustc");
    (cargo, rustc)
}

/// リポジトリの `runner/`（同梱の許可クレートの一覧）。
fn bundled_runner() -> RunnerDir {
    RunnerDir::new(Path::new(env!("CARGO_MANIFEST_DIR")).join("../runner"))
}

/// 一時ディレクトリに置いた、許可クレートが空の一覧の `runner/`。
fn empty_runner(temp: &TempDir) -> RunnerDir {
    let runner = RunnerDir::new(temp.path().join("runner"));
    fs::create_dir_all(runner.root()).unwrap();
    fs::write(runner.allowed_crates(), EMPTY_ALLOWED_CRATES).unwrap();
    fs::write(runner.cargo_lock(), EMPTY_CARGO_LOCK).unwrap();
    runner
}

fn spec(
    runner: RunnerDir,
    workspace: &WorkspaceDir,
    tools: (PathBuf, PathBuf),
    copy_validate_target: bool,
) -> PreparationSpec {
    PreparationSpec {
        runner,
        workspace: workspace.clone(),
        cargo: tools.0,
        rustc: tools.1,
        copy_validate_target,
    }
}

/// 最後まで動いて書いた記録。`prepared.json` に書いたものと同じであることも確かめる。
fn finished(outcome: PreparationOutcome, workspace: &WorkspaceDir) -> PreparedRecord {
    let PreparationOutcome::Finished(record) = outcome else {
        panic!("最後まで動かない: {outcome:?}");
    };
    assert_eq!(
        read_prepared(workspace).unwrap().as_ref(),
        Some(&record),
        "prepared.json"
    );
    record
}

/// 成功の記録が、仕様の項目を持つ。
fn assert_ready(record: &PreparedRecord, runner: &RunnerDir, rustc: &Path) {
    assert_eq!(
        record.status,
        PreparedStatus::Ready,
        "error: {:?}",
        record.error
    );
    assert_eq!(record.error, None);
    assert_eq!(record.crates_hash, crates_hash(runner).unwrap());
    assert_eq!(
        Some(&record.rustc_version),
        rustc_verbose_version(rustc).as_ref()
    );
    assert!(
        chrono::DateTime::parse_from_rfc3339(&record.prepared_at).is_ok(),
        "{}",
        record.prepared_at
    );
}

/// 手順の 1・2 のとおりに `allcrates/` と `warmup/` を作り、`target/` に `warmup/` をビルドした。
fn assert_built_warmup(workspace: &WorkspaceDir, runner: &RunnerDir) {
    let allcrates = workspace.allcrates();
    assert_eq!(
        fs::read_to_string(allcrates.join("Cargo.toml")).unwrap(),
        format!(
            "[package]\nname = \"progrust_allowed_crates\"\nversion = \"0.1.0\"\nedition = \"2024\"\n\n{}",
            fs::read_to_string(runner.allowed_crates()).unwrap()
        )
    );
    assert_eq!(
        fs::read_to_string(allcrates.join("src/lib.rs")).unwrap(),
        ""
    );

    let warmup = workspace.warmup();
    let manifest: toml::Table = fs::read_to_string(warmup.join("Cargo.toml"))
        .unwrap()
        .parse()
        .unwrap();
    assert_eq!(
        manifest["package"]["name"].as_str(),
        Some("progrust_warmup")
    );
    assert_eq!(manifest["package"]["edition"].as_str(), Some("2024"));
    let dependencies = manifest["dependencies"].as_table().unwrap();
    assert_eq!(
        dependencies.keys().collect::<Vec<_>>(),
        ["progrust_allowed_crates"]
    );
    assert_eq!(
        dependencies["progrust_allowed_crates"]["path"].as_str(),
        Some("../allcrates")
    );
    assert_eq!(
        fs::read_to_string(warmup.join("src/main.rs")).unwrap(),
        "fn main() {}\n"
    );
    assert!(warmup.join("Cargo.lock").is_file());

    // cargo build と cargo test --no-run のビルド先は target/ で、warmup/ の下には作らない。
    assert!(workspace.target().join("debug/progrust_warmup").is_file());
    assert!(!warmup.join("target").exists());
    // 同じビルド先でもう一度動かすと、どちらも何もコンパイルしない（初回準備で両方をビルドした）。
    let envs = [("CARGO_TARGET_DIR", workspace.target())];
    for args in [&["build"][..], &["test", "--no-run"][..]] {
        assert_eq!(
            compiled_packages(&warmup, &envs, args),
            Vec::<String>::new(),
            "warmup/ の {args:?}"
        );
    }
}

/// `cargo` を `args` で `dir` で動かし、cargo がコンパイルしたパッケージの名前を返す。失敗したら panic する。
fn compiled_packages<K, V>(dir: &Path, envs: &[(K, V)], args: &[&str]) -> Vec<String>
where
    K: AsRef<std::ffi::OsStr>,
    V: AsRef<std::ffi::OsStr>,
{
    let output = Command::new(env!("CARGO"))
        .args(args)
        .current_dir(dir)
        .envs(envs.iter().map(|(key, value)| (key, value)))
        .env("CARGO_TERM_COLOR", "never")
        .output()
        .unwrap();
    let stderr = String::from_utf8_lossy(&output.stderr);
    assert!(
        output.status.success(),
        "cargo {args:?} が失敗した:\n{stderr}"
    );
    stderr
        .lines()
        .filter_map(|line| line.trim_start().strip_prefix("Compiling "))
        .map(|rest| {
            rest.split_whitespace()
                .next()
                .unwrap_or_default()
                .to_string()
        })
        .collect()
}

/// `dir` の下（深さによらない）の、すべてのファイルとディレクトリのパス。手順の 4 のテスト（macOS だけ）で使う。
#[cfg(target_os = "macos")]
fn all_entries(dir: &Path) -> Vec<PathBuf> {
    let mut entries = Vec::new();
    let mut pending = vec![dir.to_path_buf()];
    while let Some(current) = pending.pop() {
        for entry in fs::read_dir(&current).unwrap() {
            let entry = entry.unwrap();
            if entry.file_type().unwrap().is_dir() {
                pending.push(entry.path());
            }
            entries.push(entry.path());
        }
    }
    entries
}

/// 名前が学習者の `project/`（パッケージ `progrust_exercise`）のビルド結果のものか。手順の 4 のテスト（macOS だけ）で使う。
#[cfg(target_os = "macos")]
fn is_exercise_build(path: &Path) -> bool {
    let name = path.file_name().unwrap().to_string_lossy();
    name.starts_with("progrust_exercise") || name.starts_with("libprogrust_exercise")
}

#[test]
fn prepares_an_empty_list_with_the_real_cargo_and_writes_ready() {
    let temp = TempDir::new().unwrap();
    let runner = empty_runner(&temp);
    let workspace = WorkspaceDir::new(temp.path().join("workspace"));
    let tools = real_cargo();
    let rustc = tools.1.clone();

    let outcome = prepare(
        &spec(runner.clone(), &workspace, tools, false),
        &Stopper::new(),
    )
    .unwrap();

    let record = finished(outcome, &workspace);
    assert_ready(&record, &runner, &rustc);
    assert_built_warmup(&workspace, &runner);
    // 手順の 4 をしないときは、target-validate/ を作らない。
    assert!(!workspace.target_validate().exists());
}

/// 前の初回準備の `allcrates/`・`warmup/` に残ったファイルは、作り直すときに消す。
#[test]
fn preparing_again_recreates_allcrates_and_warmup() {
    let temp = TempDir::new().unwrap();
    let runner = empty_runner(&temp);
    let workspace = WorkspaceDir::new(temp.path().join("workspace"));
    for stale in [
        workspace.allcrates().join("src/old.rs"),
        workspace.warmup().join("src/old.rs"),
    ] {
        fs::create_dir_all(stale.parent().unwrap()).unwrap();
        fs::write(&stale, "// 前の初回準備").unwrap();
    }
    fs::write(
        workspace.warmup().join("Cargo.lock"),
        "# 書き換えられた lock",
    )
    .unwrap();

    let record = finished(
        prepare(
            &spec(runner.clone(), &workspace, real_cargo(), false),
            &Stopper::new(),
        )
        .unwrap(),
        &workspace,
    );

    assert_eq!(record.status, PreparedStatus::Ready, "{:?}", record.error);
    assert!(!workspace.allcrates().join("src/old.rs").exists());
    assert!(!workspace.warmup().join("src/old.rs").exists());
    assert_built_warmup(&workspace, &runner);
}

/// 手順の 4: `target/` を `target-validate/` に複製し、学習者の `project/` のビルド結果を消す。
#[cfg(target_os = "macos")]
#[test]
fn prepares_an_empty_list_and_copies_target_for_validation() {
    let temp = TempDir::new().unwrap();
    let runner = empty_runner(&temp);
    let workspace = WorkspaceDir::new(temp.path().join("workspace"));
    let tools = real_cargo();
    let rustc = tools.1.clone();

    // 前の初回準備の後に、学習者が許可クレートを使う演習の project/ を target/ にビルドした結果。
    // パッケージ名が同じ progrust_exercise なので、検証のビルド先に残すと取り違える（ADR 0098）。
    let files = BTreeMap::from([(
        "src/main.rs".to_string(),
        "fn main() {}\n\n#[cfg(test)]\nmod tests {\n    #[test]\n    fn ok() {}\n}\n".to_string(),
    )]);
    assemble_project(&workspace, &runner, &[], &files).unwrap();
    let envs = [("CARGO_TARGET_DIR", workspace.target())];
    for args in [&["build"][..], &["test", "--no-run"][..]] {
        assert_eq!(
            compiled_packages(&workspace.project(), &envs, args),
            ["progrust_exercise"]
        );
    }
    let learner_builds: Vec<PathBuf> = all_entries(&workspace.target())
        .into_iter()
        .filter(|path| is_exercise_build(path))
        .collect();
    assert!(!learner_builds.is_empty());
    // 前の複製（target-validate/）。
    let stale = workspace.target_validate().join("stale");
    fs::create_dir_all(workspace.target_validate()).unwrap();
    fs::write(&stale, "前の複製").unwrap();

    let record = finished(
        prepare(
            &spec(runner.clone(), &workspace, tools, true),
            &Stopper::new(),
        )
        .unwrap(),
        &workspace,
    );

    assert_ready(&record, &runner, &rustc);
    assert_built_warmup(&workspace, &runner);
    // target/ の中身（warmup のビルド結果と、その fingerprint）が複製されている。
    let copied = all_entries(&workspace.target_validate());
    assert!(
        workspace
            .target_validate()
            .join("debug/progrust_warmup")
            .is_file()
    );
    assert!(
        copied
            .iter()
            .any(|path| path.file_name().unwrap() == "bin-progrust_warmup"),
        "warmup の fingerprint が無い"
    );
    // 前の複製は残らない。
    assert!(!stale.exists());
    // 学習者のビルド結果は、target-validate/ からだけ消える。
    let left: Vec<&PathBuf> = copied
        .iter()
        .filter(|path| is_exercise_build(path))
        .collect();
    assert!(left.is_empty(), "target-validate/ に残った: {left:?}");
    for path in &learner_builds {
        assert!(path.exists(), "{}", path.display());
    }
}

/// `--version` 以外では失敗する偽の `cargo` では、`failed` とエラーの内容を書く。
#[test]
fn a_failing_cargo_writes_failed_with_the_error() {
    let temp = TempDir::new().unwrap();
    let runner = empty_runner(&temp);
    let workspace = WorkspaceDir::new(temp.path().join("workspace"));
    let fake = FakeRust::new("1.100.0");
    let tools = (fake.cargo().to_path_buf(), fake.rustc().to_path_buf());

    let record = finished(
        prepare(
            &spec(runner.clone(), &workspace, tools, false),
            &Stopper::new(),
        )
        .unwrap(),
        &workspace,
    );

    assert_eq!(record.status, PreparedStatus::Failed);
    let error = record.error.as_deref().unwrap();
    // どの段で失敗したかと、cargo の標準エラー出力の末尾。
    assert!(
        error.starts_with("`cargo build`が失敗しました（終了コード 1）。"),
        "{error}"
    );
    assert!(error.contains("fake cargo: 対応していない引数"), "{error}");
    // 失敗の記録にも、使った一覧のハッシュ値と rustc の出力を書く。
    assert_eq!(record.crates_hash, crates_hash(&runner).unwrap());
    assert_eq!(
        Some(&record.rustc_version),
        rustc_verbose_version(fake.rustc()).as_ref()
    );
    assert!(chrono::DateTime::parse_from_rfc3339(&record.prepared_at).is_ok());
}

/// `rustc -vV` を実行できないときは、cargo を動かさずに `failed` を書く。
#[test]
fn a_rustc_that_cannot_run_writes_failed() {
    let temp = TempDir::new().unwrap();
    let runner = empty_runner(&temp);
    let workspace = WorkspaceDir::new(temp.path().join("workspace"));
    let missing_rustc = temp.path().join("missing/rustc");
    let tools = (real_cargo().0, missing_rustc);

    let record = finished(
        prepare(&spec(runner, &workspace, tools, false), &Stopper::new()).unwrap(),
        &workspace,
    );

    assert_eq!(record.status, PreparedStatus::Failed);
    let error = record.error.as_deref().unwrap();
    assert!(error.contains("rustc -vV"), "{error}");
    assert!(!workspace.target().exists());
}

/// 同梱のファイルを読めないときは、そのファイルを示して `failed` を書く。
#[test]
fn missing_bundled_files_write_failed() {
    let temp = TempDir::new().unwrap();
    let runner = empty_runner(&temp);
    fs::remove_file(runner.cargo_lock()).unwrap();
    let workspace = WorkspaceDir::new(temp.path().join("workspace"));

    let record = finished(
        prepare(
            &spec(runner, &workspace, real_cargo(), false),
            &Stopper::new(),
        )
        .unwrap(),
        &workspace,
    );

    assert_eq!(record.status, PreparedStatus::Failed);
    let error = record.error.as_deref().unwrap();
    assert!(error.contains("Cargo.lock"), "{error}");
}

/// 同梱の一覧（`rand`）で初回準備をした後は、`rand` を使う演習も使わない演習も `--offline` でビルドでき、
/// `rand` を使う演習で依存を作り直さない。クレートをダウンロードするので、ネットワークが要る。
#[test]
fn with_network_prepares_the_bundled_crates_and_builds_exercises_offline_without_rebuilding() {
    let temp = TempDir::new().unwrap();
    let runner = bundled_runner();
    let workspace = WorkspaceDir::new(temp.path().join("workspace"));
    let tools = real_cargo();
    let rustc = tools.1.clone();
    let copy_validate_target = cfg!(target_os = "macos");

    let record = finished(
        prepare(
            &spec(runner.clone(), &workspace, tools, copy_validate_target),
            &Stopper::new(),
        )
        .unwrap(),
        &workspace,
    );
    assert_ready(&record, &runner, &rustc);
    assert_built_warmup(&workspace, &runner);
    assert_eq!(workspace.target_validate().is_dir(), copy_validate_target);

    let exercises: [(Vec<String>, &str); 2] = [
        (
            vec!["rand".to_string()],
            "fn roll() -> u32 {\n    rand::random_range(1..=6)\n}\n\n\
             fn main() {\n    println!(\"{}\", roll());\n}\n\n\
             #[cfg(test)]\nmod tests {\n    #[test]\n    fn in_range() {\n        \
             assert!((1..=6).contains(&super::roll()));\n    }\n}\n",
        ),
        (
            Vec::new(),
            "fn main() {\n    println!(\"Hello\");\n}\n\n\
             #[cfg(test)]\nmod tests {\n    #[test]\n    fn ok() {}\n}\n",
        ),
    ];
    for (dependencies, main_rs) in &exercises {
        let files = BTreeMap::from([("src/main.rs".to_string(), main_rs.to_string())]);
        assemble_project(&workspace, &runner, dependencies, &files).unwrap();
        for args in [
            &["build", "--offline"][..],
            &["test", "--offline", "--no-run"][..],
        ] {
            // 演習のパッケージだけをコンパイルし、rand などの依存（progrust_allowed_crates を含む）は作り直さない。
            assert_eq!(
                compiled_packages(
                    &workspace.project(),
                    &build_env(&workspace, dependencies),
                    args
                ),
                ["progrust_exercise"],
                "{dependencies:?} {args:?}"
            );
        }
    }
}
